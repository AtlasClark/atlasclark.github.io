/* "M x y L x y Q cx cy x y C x1 y1 x2 y2 x y Z" to the [cmd, ...nums] form. */
function d(str) {
  const t = str.trim().split(/[\s,]+/), out = [], need = { M: 2, L: 2, Q: 4, C: 6, Z: 0 };
  for (let i = 0; i < t.length;) {
    const c = t[i++], n = need[c];
    out.push([c, ...t.slice(i, i + n).map(Number)]);
    i += n;
  }
  return out;
}
const E = (x, y, rx, ry, fill, o = {}) => Object.assign({ t: "ell", x, y, rx, ry, rot: o.rot || 0, a0: o.a0 ?? 0, a1: o.a1 ?? 6.2832 },
  fill ? { fill } : {}, o.chord ? { chord: true } : {}, o.stroke ? { stroke: o.stroke, w: o.w || 0.03 } : {}, o.show ? { show: o.show } : {});
const P = (path, fill) => ({ t: "path", d: d(path), fill });
const S = (path, stroke, w, round = true) => Object.assign({ t: "path", d: d(path), stroke, w }, round ? { cap: "round" } : {});
const EYE = (x, y, s) => s ? { t: "eye", x, y, s } : { t: "eye", x, y };
const ALIVE = s => Object.assign(s, { show: "alive" });
const LINE = (s, stroke, w) => Object.assign(s, { stroke, w });
const f4 = v => v.toFixed(4);
const PI = 3.1416, TAU = 6.2832;

/* An ellipse with a wedge cut out, opening toward angle g (a claw). */
function claw(cx, cy, rx, ry, g, gap = 0.5, steps = 14) {
  const pts = [];
  for (let i = 0; i <= steps; i++) {
    const a = g + gap + i / steps * (2 * Math.PI - 2 * gap);
    pts.push(f4(cx + rx * Math.cos(a)) + " " + f4(cy + ry * Math.sin(a)));
  }
  return "M " + f4(cx + rx * 0.25 * Math.cos(g)) + " " + f4(cy + ry * 0.25 * Math.sin(g)) + " L " + pts.join(" L ") + " Z";
}
function spikes(cx, cy, r0, r1, n, stroke, w, from = 0) {
  const out = [];
  for (let i = 0; i < n; i++) {
    const a = from + i / n * 2 * Math.PI;
    out.push(S("M " + f4(cx + r0 * Math.cos(a)) + " " + f4(cy + r0 * Math.sin(a)) +
               " L " + f4(cx + r1 * Math.cos(a)) + " " + f4(cy + r1 * Math.sin(a)), stroke, w));
  }
  return out;
}

