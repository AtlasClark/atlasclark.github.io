/* The second pen's built-in drawings (kinds 27-51), in the Pet Studio's shape format
   (see petdefs.js), so every one can be redrawn there. Units of r, origin at the
   waterline, facing left. Index i here is kind PEN2_FIRST + i, with the same rarity
   as first-pen kind i. Colours: body / light / dark follow each catch's hue. */

const HUE = (dh, s, l, a = 1) => ({ hue: 1, dh, s, l, a });
const FIX = c => ({ c });
const base = extra => Object.assign({ body: HUE(0, 62, 58), light: HUE(0, 62, 70), dark: HUE(0, 55, 42),
                                      ink: FIX("#2a2118"), white: FIX("#f4f7f9") }, extra || {});

/* "M x y L x y Q cx cy x y C x1 y1 x2 y2 x y Z" to the [cmd, ...nums] form. */
function d(str) {
  const t = str.trim().split(/[\s,]+/), out = [], need = { M: 2, L: 2, Q: 4, C: 6, Z: 0 };
  for (let i = 0; i < t.length;) {
    const c = t[i++], n = need[c];
    out.push([c, ...t.slice(i, i + n).map(Number)]);
    i += n;
  }
  return out;
}
const E = (x, y, rx, ry, fill, o = {}) => Object.assign({ t: "ell", x, y, rx, ry, rot: o.rot || 0, a0: o.a0 ?? 0, a1: o.a1 ?? 6.2832 },
  fill ? { fill } : {}, o.chord ? { chord: true } : {}, o.stroke ? { stroke: o.stroke, w: o.w || 0.03 } : {}, o.show ? { show: o.show } : {});
const P = (path, fill) => ({ t: "path", d: d(path), fill });
const S = (path, stroke, w, round = true) => Object.assign({ t: "path", d: d(path), stroke, w }, round ? { cap: "round" } : {});
const EYE = (x, y, s) => s ? { t: "eye", x, y, s } : { t: "eye", x, y };

function star(cx, cy, ro, ri, n = 5) {
  const pts = [];
  for (let i = 0; i < n * 2; i++) {
    const a = -Math.PI / 2 + i * Math.PI / n, r = i % 2 ? ri : ro;
    pts.push((i ? "L " : "M ") + (cx + r * Math.cos(a)).toFixed(4) + " " + (cy + r * Math.sin(a)).toFixed(4));
  }
  return pts.join(" ") + " Z";
}
function spikes(cx, cy, r0, r1, n, stroke, w) {
  const out = [];
  for (let i = 0; i < n; i++) {
    const a = i / n * 2 * Math.PI;
    out.push(S("M " + (cx + r0 * Math.cos(a)).toFixed(4) + " " + (cy + r0 * Math.sin(a)).toFixed(4) +
               " L " + (cx + r1 * Math.cos(a)).toFixed(4) + " " + (cy + r1 * Math.sin(a)).toFixed(4), stroke, w));
  }
  return out;
}

